module Help
    ( helpText
    , showHelp
    ) where

helpText :: String
helpText = unlines
    [ "NAME"
    , "     hsbisync - 两个目录之间的双向文件同步工具"
    , ""
    , "SYNOPSIS"
    , "     hsbisync sync <profile>"
    , "     hsbisync sync <profile> <root1> <root2>"
    , "     hsbisync diff <profile>"
    , "     hsbisync profile"
    , "     hsbisync help | --help"
    , ""
    , "DESCRIPTION"
    , "     把两个目录（本机与本机，或本机与 SSH 远端）双向同步成一致。"
    , "     远端只需 PATH 里有可执行的 hsbisync，由本机经 ssh 拉起，在"
    , "     stdin/stdout 上跑二进制消息协议充当 helper。"
    , ""
    , "SUBCOMMANDS"
    , "     help"
    , "         打印本手册；--help 等价，内容逐字节相同。带多余参数报用法错误。"
    , ""
    , "     sync <profile>"
    , "         读 .bisync/<profile>/repo 里记的对端地址，同步当前目录。"
    , "         两端同步根须已存在：不建目录，不重写 repo。"
    , ""
    , "     sync <profile> <root1> <root2>"
    , "         显式给出两个根来同步。缺的同步根只建一层（父目录须已存在）；"
    , "         把对端地址写入两端的 .bisync/<profile>/repo，之后可用免参形式。"
    , ""
    , "     diff <profile>"
    , "         只读预览：当前目录相对上次基线的变化，标出变的维度"
    , "         （长度、mtime 旧值到新值，时间按本地时区显示）。不写状态。"
    , ""
    , "     profile"
    , "         列出 .bisync/ 下所有 profile 及各自的 repo 与 ignore 内容。"
    , "         只读，不带参数。"
    , ""
    , "     --helper --passcode=dontrunyourself --root=<路径> [--tag=<profile>]"
    , "         内部使用：远端那半边进程，由本机经 ssh 拉起。"
    , "         --passcode 防止误敲。"
    , ""
    , "ROOTS"
    , "     根地址两种写法："
    , "         /本机/路径"
    , "         [user@]host:/远端/路径"
    , ""
    , "SYNC PROCEDURE"
    , "     一次 sync 分 6 步进行："
    , ""
    , "     [1/6] Sync prepare ..."
    , "         目录 -> 握手 -> repo。"
    , "         目录：显式地址模式缺则建（只建一层）；免参模式只检查存在。"
    , "         握手：ssh 过去用 command -v hsbisync 取得绝对路径，再拉起"
    , "         helper；helper 自报可执行路径与家目录，此后所有远端调用都"
    , "         走这个绝对路径。repo 只有显式地址模式才写入两端。"
    , ""
    , "     [2/6] Syncing ignore rules ..."
    , "         无条件把 .bisync/<profile>/ignore 在两端对齐：较新的一端"
    , "         覆盖较旧的一端。必须先对齐，之后两端扫出的文件集合才可比。"
    , "         此步之后 ignore 文件不再参与文件同步。"
    , ""
    , "     [3/6] Syncing symlinks ..."
    , "         只比较链接自身的 lstat（长度即指向字符串长度，另带自己的"
    , "         mtime），不跟随。两端链接结构若没达成一致（有未消解的冲突、"
    , "         有动作没落地、或确认处拒绝），则第 4 到 6 步整体跳过。"
    , "         原因：文件阶段的比较键是 相对路径 + (长度, mtime)，前提是"
    , "         同一路径在两端指同一个对象；链接没对齐时该前提不成立。"
    , ""
    , "     [4/6] Reading states ..."
    , "         两端并行扫描（各自按已统一的 ignore 过滤），与各自基线比较。"
    , "         扫描深度优先，跟随软链接（指向目录的链接当目录走进去）；"
    , "         悬空链接不特殊处理。顺带用 rmdir 清空目录（不递归删除），"
    , "         两端各清各的。"
    , ""
    , "     [5/6] Computing sync actions ..."
    , "         比较键 = 相对路径 + 长度 + 整数秒 mtime；模式不参与。"
    , "         可自动消解的假冲突："
    , "             双方都是新增或更新，且长度与整数秒 mtime 相同"
    , "                 -> 判作已同步，不传输"
    , "             双方都是删除 -> 只记一笔账，不动文件"
    , "         删除只在对方未变时才传播；对方也变了则是冲突。"
    , "         真正的冲突标为无法消解，不自动处理。若无任何动作，"
    , "         不进第 6 步。"
    , ""
    , "         确有动作时，对被判为要传输的或冲突的、且两端长度相同的"
    , "         文件做额外内容校验：逐对比 SHA-512，相同的改成只记账"
    , "         并把较旧那端的 mtime 对齐到较新那端，不同的维持原判。"
    , ""
    , "     [6/6] Sync and record files ..."
    , "         只在确有动作时才进入。确认前列出最终动作，确认后才真正"
    , "         传输与删除，并写入新基线。只剩无法消解的冲突时跳过确认。"
    , "         落盘是原子的：在目标同目录写 .hsbisync-tmp<pid>-<序号>.tmp，"
    , "         设好权限与 mtime，哈希校验通过后才 rename 到目标名。"
    , "         校验在 rename 之前，不通过则丢临时文件，原文件不受影响。"
    , ""
    , "FILES"
    , "     .bisync/<profile>/repo"
    , "         对端地址一行。sync <profile> <root1> <root2> 时自动写入。"
    , ""
    , "     .bisync/<profile>/ignore"
    , "         忽略规则清单，gitignore 语法。第 2 步自动在两端对齐。"
    , ""
    , "     基线三件套（文件树一套，软链接树一套，两套同构）："
    , ""
    , "     .bisync/<profile>/state          上次同步时的基准快照"
    , "     .bisync/<profile>/added          上次同步后新增的条目（追加流水）"
    , "     .bisync/<profile>/deleted        上次同步后删除的名字（追加流水）"
    , "     .bisync/<profile>/link_state     同上，软链接树"
    , "     .bisync/<profile>/link_added"
    , "     .bisync/<profile>/link_deleted"
    , ""
    , "     state 是上次同步时的快照，added / deleted 是此后的增量流水。"
    , "     快照单独无法判断变化方向：某文件一端有、另一端没有，是新增"
    , "     还是删除？有了基线才有参照，变化才有方向。"
    , ""
    , "     每个 profile 对应一个同步关系（一个对端 + 一组 ignore 规则），"
    , "     两端各存自己那份。.bisync 目录本身不参与同步，ignore 文件由"
    , "     第 2 步对齐。"
    , ""
    , "IGNORE RULES"
    , "     .bisync/<profile>/ignore 按 gitignore 语法（gitignore-ospath"
    , "     实现）在扫描时过滤文件树：被忽略的条目对同步不可见，不删、"
    , "     不同步。ignore 文件本身由第 2 步在两端对齐。"
    , ""
    , "     隐藏文件不特殊对待，.git/ 等同样参与同步。.bisync 目录本身"
    , "     始终跳过。工具的临时文件（.hsbisync-tmp*）同样参与同步。"
    , ""
    , "EXIT STATUS"
    , "     0    正常结束。包括 Nothing to do.、确认处拒绝而打印的"
    , "          Aborted.、以及链接阶段中止只打印一行说明的情况。"
    , "     1    参数错误，或运行前检查失败。"
    , "     诊断信息打到标准输出，格式为 Error: <说明>。"
    , ""
    , "ENVIRONMENT"
    , "     进程内固定 UTF-8（文件名、参数、内容、句柄），与 LANG、LC_ALL"
    , "     无关，本地与远端 helper 行为一致。"
    , ""
    , "LIMITATIONS"
    , "     远端要求：ssh 免密登录，且登录 shell 的 PATH 里有同版本的"
    , "     hsbisync。"
    , ""
    , "     冲突：两边同时改了同一个文件即冲突，不自动合并，只列出交人"
    , "     处理。不保存历史版本，不能回滚。"
    , ""
    , "     文件传输：整文件读入内存后写出，传超大文件可能 OOM。无增量"
    , "     传输，无断点续传。中断留下的临时文件不被自动清理，也可能被"
    , "     当作普通文件同步。不做 fsync。"
    , ""
    , "EXAMPLES"
    , "     首次同步："
    , "         hsbisync sync local xx-cli user@host:project/xx-cli"
    , ""
    , "     之后："
    , "         hsbisync sync local"
    , ""
    , "     查看变化："
    , "         hsbisync diff local"
    , ""
    , "     列出所有 profile："
    , "         hsbisync profile"
    ]

showHelp :: IO ()
showHelp = putStr helpText
